export function getChapter(chapterId) {
  return chapters.find((c) => c.id === chapterId)
}

export function getLesson(chapterId, lessonId) {
  const ch = getChapter(chapterId)
  if (!ch) return null
  const idx = ch.lessons.findIndex((l) => l.id === lessonId)
  if (idx === -1) return null
  return {
    chapter: ch,
    lesson: ch.lessons[idx],
    index: idx,
    prev: ch.lessons[idx - 1] || null,
    next: ch.lessons[idx + 1] || null,
  }
}

export const readyChapters = chapters.filter((c) => c.ready)
